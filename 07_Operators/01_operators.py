a = 34

b =2 

print("a + b =", a + b)  # Addition
print("a - b =", a - b)  # Subtraction
print("a * b =", a * b)  # Multiplication
print("a / b =", a / b)  # Division
print("a % b =", a % b)  # Modulus
print("a ** b =", a ** b)  # Exponentiation
print("a // b =", a // b)  # Floor Division


#conditional operators
print("a > b =", a > b)  # Greater than
print("a < b =", a < b)  # Less than
print("a >= b =", a >= b)  # Greater than or equal to
print("a <= b =", a <= b)  # Less than or equal to  
print("a == b =", a == b)  # Equal to
print("a != b =", a != b)  # Not equal to

#Logical operators
c = True
d = False

print("c and d =", c and d)  # Logical AND
print("c or d =", c or d)  # Logical OR
print("not c =", not c)  # Logical NOT


#assignment operators

x = 10

print("x =", x)  # Initial value of x

x += 5  # Equivalent to x = x + 5
print("x after x += 5:", x)

x -= 3  # Equivalent to x = x - 3
print("x after x -= 3:", x) 

x *= 2  # Equivalent to x = x * 2
print("x after x *= 2:", x) 

x /= 4  # Equivalent to x = x / 4
print("x after x /= 4:", x) 

x %= 3  # Equivalent to x = x % 3
print("x after x %= 3:", x)


#membership operators
my_list = [1, 2, 3, 4, 5]

print("3 in my_list =", 3 in my_list)  # Check if 3 is in the list
print("6 not in my_list =", 6 not in my_list)  # Check if

