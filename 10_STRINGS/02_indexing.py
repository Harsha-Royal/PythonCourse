name = "Harsha"

print(name[0])  # Output: H
print(name[1])  # Output: a
print(name[2])  # Output: r
print(name[3])  # Output: s
print(name[4])  # Output: h
print(name[5])  # Output: a

print(name[-1])  # Output: a (last character)
print(name[-2])  # Output: h (second last character)
print(name[-3])  # Output: s (third last character)
print(name[-4])  # Output: r (fourth last character)
print(name[-5])  # Output: a (fifth last character)
print(name[-6])  # Output: H (sixth last character)