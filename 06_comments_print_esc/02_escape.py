print("Hey how are you? \n i`m fine")  # \n is used to print in new line

print("Hey how are you? \t i`m fine")  # \t is used to print in tab space

print("Hey how are you? \b i`m fine")  # \b is used to print in backspace

print("Hey how are you? \\ i`m fine")  # \\ is used to print a backslash

print("Hey how are you? \' i`m fine")  # \' is used to print a single quote

print("Hey how are you? \" i`m fine")  # \" is used to print a double quote 