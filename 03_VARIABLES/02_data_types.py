# Python supports various data types. Some of the commonly used data types are:
#   Integers (int): Whole numbers without a decimal point. Example: 5, -10, 0
#   Floating-point numbers (float): Numbers with a decimal point. Example: 3.14, -2.5
#   Strings (str): Sequence of characters enclosed in single or double quotes. Example: "Hello", 'Python'
#   Booleans (bool): Represents either True or False. Example: True, False
#   Lists (list): Ordered collection of items enclosed in square brackets. Example: [1, 2, 3], ['apple', 'banana']
#   Tuples (tuple): Ordered collection of items enclosed in parentheses. Example: (1, 2, 3), ('a', 'b', 'c')
#   Sets (set): Unordered collection of ***unique items enclosed in curly braces. Example: {1, 2, 3}, {'apple', 'banana'}
#   Dictionaries (dict): Unordered collection of key-value pairs enclosed in curly braces. Example: {'name': 'Alice', 'age': 25}


age = 29
name = "Harsha" 


cgpa = 9.5

print("Age:", age , "type:", type(age))
print("Name:", name, "type:", type(name))
